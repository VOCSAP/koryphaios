/**
 * Validate the operator's Dockerfile fragment and compose the full custom
 * Dockerfile. A FROM line is refused rather than honoured: the base is the
 * app's contract (user kory, CLAUDE_CONFIG_DIR, the CLI preinstalled) and a
 * fragment silently swapping it would produce containers that fail far from
 * the cause. Returns null for an empty/blank fragment (nothing to build).
 * The fragment is OPERATOR app-state input (never repo-provided), so this is
 * a UX guard, not a security boundary.
 */
export function composeCustomDockerfile(fragment: string): string | null {
  const trimmed = fragment.trim()
  if (!trimmed) return null
  if (/^\s*FROM\b/im.test(trimmed)) throw new Error('custom-fragment-from')
  return `# Generated by Koryphaios — operator customisation on top of the base image.\nFROM ${SANDBOX_IMAGE_DEFAULT}\n${trimmed}\n`
}
