/**
 * The credentials volume is app-wide, so every operation on it runs in a
 * throwaway container mounting nothing else — no /work, no run dir, no peers
 * dir, no published ports — the smallest possible mount set.
 */
function authVolumeMount(): string[] {
  return ['-v', `${SANDBOX_AUTH_VOLUME}:${SANDBOX_HOME}/.claude`, '-e', SANDBOX_CONFIG_DIR_ENV]
}

/**
 * The auth terminal command (SBX3): plain `claude` in a throwaway container —
 * the CLI detects the missing login and walks the operator through the OAuth
 * flow. The Deck polls the credentials file and kills this PTY on success.
 * `--rm` so an abandoned login leaves nothing behind.
 */
export function buildAuthCommand(engine: SandboxEngine, image: string): string {
  return `${engine} run --rm -it ${authVolumeMount().join(' ')} ${image} bash -lc claude`
}

/**
 * Checks both the credentials file and hasCompletedOnboarding in .claude.json:
 * the CLI writes credentials as soon as OAuth succeeds but keeps onboarding
 * open, and the login dialog kills the login PTY the instant a credentials-only
 * check would pass.
 * On a missing .claude.json a bare grep -q exits 2; the if/else collapses every
 * miss to exit 1 so probeAuth reads it as a plain not-signed-in rather than
 * engine trouble.
 */
export function buildAuthProbeArgs(image: string): string[] {
  return [
    'run',
    '--rm',
    ...authVolumeMount(),
    image,
    'sh',
    '-c',
    `if test -s ${SANDBOX_CREDENTIALS_FILE} && grep -qs hasCompletedOnboarding ${SANDBOX_CLAUDE_JSON}; then exit 0; else exit 1; fi`
  ]
}

/** Arg vector wiping the credentials file ("disconnect", guarded upstream). */
export function buildAuthPurgeArgs(image: string): string[] {
  return ['run', '--rm', ...authVolumeMount(), image, 'rm', '-f', SANDBOX_CREDENTIALS_FILE]
}

/**
 * Container-side transcript dir for a host cwd (M2 resume): Claude writes
 * `~/.claude/projects/<encoded cwd>/<id>.jsonl`, and inside the sandbox the
 * cwd is the CONTAINER path — so the encoding must run on the mapped path,
 * not the host one. `~/.claude` is the auth volume, so these transcripts
 * survive a container rebuild.
 */
export function containerTranscriptDir(
  cwdHost: string,
  projectDir: string,
  plat: NodeJS.Platform = platform()
): string | null {
  const containerCwd = mapHostPathToContainer(cwdHost, projectDir, plat)
  // Outside the mount there is no container-side transcript dir to look in —
  // null so the caller reports "unknown", never an empty (= "no transcript")
  // answer that would silently downgrade a resume to a fresh session.
  if (containerCwd === null) return null
  return `${SANDBOX_HOME}/.claude/projects/${encodeProjectDir(containerCwd)}`
}

/**
 * Arg vector listing a transcript dir as `<name>\t<mtime seconds>` rows.
 * GNU find (debian base image); a missing dir exits non-zero → empty list.
 */
export function buildTranscriptListArgs(name: string, dir: string): string[] {
  return ['exec', name, 'find', dir, '-maxdepth', '1', '-name', '*.jsonl', '-printf', '%f\\t%T@\\n']
}

/** Parse `buildTranscriptListArgs` stdout into transcript entries. */
export function parseTranscriptList(stdout: string): { id: string; mtimeMs: number }[] {
  const out: { id: string; mtimeMs: number }[] = []
  for (const line of stdout.split('\n')) {
    const [file, stamp] = line.split('\t')
    if (!file || !file.endsWith('.jsonl')) continue
    const seconds = Number.parseFloat(stamp ?? '')
    out.push({
      id: file.slice(0, -'.jsonl'.length),
      mtimeMs: Number.isFinite(seconds) ? seconds * 1000 : 0
    })
  }
  return out
}

/**
 * `docker cp -L <hostPath> <container>:<containerPath>` (config projection, M2).
 *
 * `-L` (follow the SOURCE link) is load-bearing, not tidiness: many operators
 * keep `~/.claude/CLAUDE.md`, `agents`, `skills` and `settings.json` as
 * symlinks into a versioned config repo. Without `-L`, `docker cp` copies the
 * LINK, which lands in the container pointing at a host path that does not
 * exist there -- so the operator's global config was silently absent from every
 * sandboxed agent while the Docker view happily reported it as projected.
 * Following the link is also the safer of the two: what crosses is a plain
 * file, never a pointer the container could resolve somewhere unexpected.
 */
export function buildCopyIntoArgs(name: string, hostPath: string, containerPath: string): string[] {
  return ['cp', '-L', hostPath, `${name}:${containerPath}`]
}

/**
 * docker cp -L overwrites a destination file but refuses to replace a
 * destination directory symlink with a real directory, so stale projected
 * entries are deleted before the copy to make it authoritative.
 * Only entries about to be re-copied are purged, never the whole allow-list, so
 * removing a host entry never deletes the container's last copy without a
 * replacement.
 */
export function buildProjectionCleanArgs(name: string, entryNames: string[]): string[] {
  // Entry names come from PROJECTED_ENTRIES via planProjection, but re-check
  // the shape anyway: a path separator (or a bare `.`/`..`, which the charset
  // alone would let through as `rm -rf ~/.claude/..`) would let a future
  // refactor reach outside ~/.claude (hostile input #4 — validate at the
  // boundary).
  //
  // `--user root`: `docker cp` writes the projected trees as ROOT, and the
  // container's default user (kory) may unlink the top-level entries (it owns
  // ~/.claude) but nothing INSIDE a root-owned dir — the first run as kory
  // sprayed hundreds of "rm: Permission denied" over plugins/.
  const safe = projectionSafeNames(entryNames)
  return ['exec', '--user', 'root', name, 'rm', '-rf', ...safe.map((n) => `${SANDBOX_CONFIG_DIR}/${n}`)]
}

/**
 * Post-projection ownership fix: `docker cp` lands the trees as root, and the
 * CLI (running as kory) then cannot WRITE its own copy — concretely
 * `plugins/installed_plugins.json` was read-only for the very process meant
 * to maintain it. The copy is the agent's to wreck (it dies with the
 * container), so kory owning it is the design, not a concession.
 */
export function buildProjectionChownArgs(name: string, entryNames: string[]): string[] {
  const safe = projectionSafeNames(entryNames)
  return [
    'exec',
    '--user',
    'root',
    name,
    'chown',
    '-R',
    `${SANDBOX_USER}:${SANDBOX_USER}`,
    ...safe.map((n) => `${SANDBOX_CONFIG_DIR}/${n}`)
  ]
}

function projectionSafeNames(entryNames: string[]): string[] {
  return entryNames.filter((n) => /^[A-Za-z0-9._-]+$/.test(n) && !/^\.+$/.test(n))
}

