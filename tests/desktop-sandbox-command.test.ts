  const out = parseModNamespaceInspection(`[{"Destination":"/opt/kory-mods/"},{"Destination":"//"},{"Destination":"/opt//"}]\t"kory"`);
  expect(out?.mounts.map((m) => m.destination)).toEqual(["/opt/kory-mods", "/", "/opt"]);
